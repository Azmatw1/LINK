function setLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    const inputs = document.querySelectorAll('[data-i18n-placeholder]');
    inputs.forEach(input => {
        const key = input.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            input.placeholder = translations[lang][key];
        }
    });

    localStorage.setItem('selectedLanguage', lang);
}

document.addEventListener('DOMContentLoaded', () => {
    
    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        const savedLang = localStorage.getItem('selectedLanguage') || 'en';
        langSelect.value = savedLang;
        setLanguage(savedLang);

        langSelect.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    }

    const togglePasswordBtn = document.getElementById('togglePassword');
    const passwordInput = document.getElementById('password');
    if (togglePasswordBtn && passwordInput) {
        togglePasswordBtn.addEventListener('click', () => {
            const isPassword = passwordInput.type === 'password';
            passwordInput.type = isPassword ? 'text' : 'password';
            togglePasswordBtn.textContent = isPassword ? '🙈' : '👁️';
        });
    }

    const loginForm = document.getElementById('loginForm');
    if (loginForm) {
        loginForm.addEventListener('submit', async (e) => {
            e.preventDefault();

            const phoneNumber = document.getElementById('phoneNumber').value.trim();
            const password = document.getElementById('password').value;

            try {
                const response = await fetch('/api/login', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ phoneNumber, password })
                });

                const data = await response.json();

                if (response.ok && data.success) {
                    localStorage.setItem('userPhone', phoneNumber);
                    localStorage.setItem('farmerPhone', phoneNumber);
                    if (data.user && data.user.full_name) {
                        localStorage.setItem('farmerName', data.user.full_name);
                    }
                    window.location.href = 'dashboard.html';
                } else {
                    alert(data.message || 'Login failed. Please check your credentials.');
                }
            } catch (error) {
                console.error('Login error:', error);
                alert('Unable to connect to the server. Please ensure the Flask backend is running.');
            }
        });
    }

    const registerForm = document.getElementById('registerForm');
    if (registerForm) {
        registerForm.addEventListener('submit', async (e) => {
            e.preventDefault();

            const fullName = document.getElementById('fullName').value.trim();
            const phoneNumber = document.getElementById('phoneNumber').value.trim();
            const state = document.getElementById('state').value.trim();
            const village = document.getElementById('village').value.trim();
            const password = document.getElementById('password').value;

            try {
                const response = await fetch('/api/register', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ fullName, phoneNumber, state, village, password })
                });

                const data = await response.json();

                if (response.ok && data.success) {
                    alert(data.message || "Account created successfully! Please log in.");
                    window.location.href = 'index.html';
                } else {
                    alert(data.message || 'Registration failed. Please check your input.');
                }
            } catch (error) {
                console.error('Registration error:', error);
                alert('Unable to connect to the server. Please ensure the Flask backend is running.');
            }
        });
    }

    const bookingForm = document.getElementById('bookingForm');
    if (bookingForm) {
        bookingForm.addEventListener('submit', async (e) => {
            e.preventDefault();

            const centerSelect = document.getElementById('centre');
            const center = centerSelect.options[centerSelect.selectedIndex].text;
            const cropSelect = document.getElementById('crop');
            const crop = cropSelect.options[cropSelect.selectedIndex].text;
            const quantity = document.getElementById('quantity').value;
            const bookingDate = document.getElementById('bookingDate').value;
            const timeSlotSelect = document.getElementById('timeSlot');
            const timeSlot = timeSlotSelect.value;

            let phone = localStorage.getItem('userPhone') || localStorage.getItem('farmerPhone');
            if (!phone) {
                phone = prompt("Please enter your registered 10-digit mobile number to confirm this booking:");
                if (!phone) {
                    alert("A mobile number is required to book a slot.");
                    return;
                }
                phone = phone.trim();
                localStorage.setItem('userPhone', phone);
                localStorage.setItem('farmerPhone', phone);
            }

            try {
                const response = await fetch('/api/book-slot', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({
                        userPhone: phone,
                        phoneNumber: phone,
                        center: center,
                        crop: crop,
                        quantity: quantity,
                        bookingDate: bookingDate,
                        timeSlot: timeSlot
                    })
                });

                const data = await response.json();

                if (response.ok && data.success) {
                    localStorage.setItem('latestToken', data.token_number);
                    if (data.booking) {
                        localStorage.setItem('latestBooking', JSON.stringify(data.booking));
                    }
                    alert("Procurement slot booked successfully! Assigned Token: " + data.token_number);
                    window.location.href = 'token.html';
                } else {
                    alert(data.message || 'Slot booking failed. Please try again.');
                }
            } catch (error) {
                console.error('Booking error:', error);
                alert('Unable to connect to the server. Please ensure the Flask backend is running.');
            }
        });
    }

    const tokenDisplay = document.getElementById('tokenNumber');
    const procurementTokenDisplay = document.getElementById('procurementToken');
    const activeBookingCard = document.getElementById('activeBookingCard');
    const noBookingCard = document.getElementById('noBookingCard');
    const procurementActiveCard = document.getElementById('procurementActiveCard');
    const procurementNoBookingCard = document.getElementById('procurementNoBookingCard');

    if (tokenDisplay || procurementTokenDisplay) {
        const userPhone = localStorage.getItem('userPhone') || localStorage.getItem('farmerPhone');

        const showNoBooking = () => {
            if (activeBookingCard) activeBookingCard.style.display = 'none';
            if (noBookingCard) noBookingCard.style.display = 'block';
            if (procurementActiveCard) procurementActiveCard.style.display = 'none';
            if (procurementNoBookingCard) procurementNoBookingCard.style.display = 'block';
            const tokenHeaderTitle = document.getElementById('tokenHeaderTitle');
            const tokenHeaderSub = document.getElementById('tokenHeaderSub');
            if (tokenHeaderTitle) tokenHeaderTitle.textContent = "My Token Pass";
            if (tokenHeaderSub) tokenHeaderSub.textContent = "Status of your crop procurement slot.";
        };

        const showActiveBooking = (tokenNum, bookingData) => {
            if (activeBookingCard) activeBookingCard.style.display = 'block';
            if (noBookingCard) noBookingCard.style.display = 'none';
            if (procurementActiveCard) procurementActiveCard.style.display = 'block';
            if (procurementNoBookingCard) procurementNoBookingCard.style.display = 'none';

            const formattedToken = tokenNum.startsWith('#') ? tokenNum : '#' + tokenNum;
            if (tokenDisplay) tokenDisplay.textContent = formattedToken;
            if (procurementTokenDisplay) procurementTokenDisplay.textContent = formattedToken;

            const tokenCenter = document.getElementById('tokenCenter');
            const tokenWindow = document.getElementById('tokenWindow');
            if (tokenCenter && bookingData && bookingData.center) {
                tokenCenter.textContent = bookingData.center;
            }
            if (tokenWindow && bookingData && bookingData.time_slot) {
                tokenWindow.textContent = bookingData.time_slot;
            }
        };

        if (!userPhone) {
            showNoBooking();
        } else {
            fetch(`/api/my-token?phone=${encodeURIComponent(userPhone)}`)
                .then(res => res.json().then(data => ({ ok: res.ok, data })))
                .then(({ ok, data }) => {
                    if (ok && data.success && data.booking) {
                        showActiveBooking(data.token_number || data.booking.token_number, data.booking);
                    } else {
                        showNoBooking();
                    }
                })
                .catch(err => {
                    console.error('Error fetching token pass:', err);
                    const cachedToken = localStorage.getItem('latestToken');
                    if (cachedToken) {
                        try {
                            const cachedBooking = JSON.parse(localStorage.getItem('latestBooking') || '{}');
                            showActiveBooking(cachedToken, cachedBooking);
                        } catch (e) {
                            showNoBooking();
                        }
                    } else {
                        showNoBooking();
                    }
                });
        }
    }

    const userTokenDisplay = document.getElementById('userTokenDisplay');
    const paymentTokenDisplay = document.getElementById('paymentTokenDisplay');

    if (userTokenDisplay || paymentTokenDisplay) {
        const userPhone = localStorage.getItem('userPhone') || localStorage.getItem('farmerPhone');

        if (!userPhone) {
            if (userTokenDisplay) userTokenDisplay.textContent = "No Active Booking";
            if (paymentTokenDisplay) paymentTokenDisplay.textContent = "No Active Booking";
        } else {
            fetch(`/api/my-token?phone=${encodeURIComponent(userPhone)}`)
                .then(res => res.json().then(data => ({ ok: res.ok, data })))
                .then(({ ok, data }) => {
                    if (ok && data.success && data.booking) {
                        const rawToken = data.booking.token_number || data.token_number;
                        const formattedToken = rawToken.startsWith('#') ? rawToken : '#' + rawToken;
                        
                        const tokenSeq = parseInt(rawToken.replace('#', ''), 10) || 1;
                        const servingSeq = Math.max(1, tokenSeq - 2);
                        const servingStr = `#${String(servingSeq).padStart(3, '0')}`;
                        const farmersAhead = Math.max(0, tokenSeq - 1);
                        const estWaitMins = farmersAhead * 10;

                        const cropQty = parseFloat(data.booking.quantity) || 0;
                        const totalPayout = cropQty * 2275;

                        if (userTokenDisplay) {
                            userTokenDisplay.textContent = formattedToken;
                            const servingElem = document.getElementById('currentlyServingDisplay');
                            if (servingElem) servingElem.textContent = servingStr;
                            const aheadElem = document.getElementById('farmersAheadDisplay');
                            if (aheadElem) aheadElem.textContent = farmersAhead;
                            const waitElem = document.getElementById('estWaitDisplay');
                            if (waitElem) waitElem.textContent = farmersAhead === 0 ? "Serving Now" : `~${estWaitMins} mins`;
                        }

                        if (paymentTokenDisplay) {
                            paymentTokenDisplay.textContent = formattedToken;
                            const amountElem = document.getElementById('paymentAmountDisplay');
                            if (amountElem) amountElem.textContent = `₹${totalPayout.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`;
                        }
                    } else {
                        if (userTokenDisplay) userTokenDisplay.textContent = "No Active Booking";
                        if (paymentTokenDisplay) paymentTokenDisplay.textContent = "No Active Booking";
                    }
                })
                .catch(err => {
                    console.error('Error fetching tracker details:', err);
                    if (userTokenDisplay) userTokenDisplay.textContent = "No Active Booking";
                    if (paymentTokenDisplay) paymentTokenDisplay.textContent = "No Active Booking";
                });
        }
    }

    const logoutLinks = document.querySelectorAll('.logout-link');
    logoutLinks.forEach(link => {
        link.addEventListener('click', () => {
            localStorage.removeItem('userPhone');
            localStorage.removeItem('farmerPhone');
            localStorage.removeItem('farmerName');
            localStorage.removeItem('latestToken');
            localStorage.removeItem('latestBooking');
        });
    });
});
